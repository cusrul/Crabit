#ifndef CRABIT_USB_COMPOSITE_CONFIG_H
#define CRABIT_USB_COMPOSITE_CONFIG_H

#define USE_USBD_COMPOSITE
#define USBD_CMPSIT_ACTIVATE_CDC       1U
#define USBD_CMPSIT_ACTIVATE_CUSTOMHID 1U
#define USBD_CMPST_MAX_CONFDESC_SZ     192U
#define USBD_COMPOSITE_USE_IAD        1U
#define USBD_MAX_SUPPORTED_CLASS      2U
#define USBD_CUSTOMHID_CTRL_REQ_GET_REPORT_ENABLED

#define CRABIT_USB_CLASS_COUNT         2U
#define CRABIT_USB_INTERFACE_COUNT    3U
#define CRABIT_USB_CDC_CLASS          0U
#define CRABIT_USB_HID_CLASS          1U

#define CRABIT_USB_CDC_IN_EP          0x81U
#define CRABIT_USB_CDC_OUT_EP         0x01U
#define CRABIT_USB_CDC_CMD_EP         0x82U
#define CRABIT_USB_HID_IN_EP          0x83U
#define CRABIT_USB_HID_OUT_EP         0x03U
#define CRABIT_USB_HID_IN_SIZE        8U
#define CRABIT_USB_HID_OUT_SIZE       2U
#define CUSTOM_HID_EPIN_ADDR          CRABIT_USB_HID_IN_EP
#define CUSTOM_HID_EPIN_SIZE          CRABIT_USB_HID_IN_SIZE
#define CUSTOM_HID_EPOUT_ADDR         CRABIT_USB_HID_OUT_EP
#define CUSTOM_HID_EPOUT_SIZE         CRABIT_USB_HID_OUT_SIZE
#define USBD_CUSTOMHID_OUTREPORT_BUF_SIZE 2U
#define USBD_CUSTOM_HID_REPORT_DESC_SIZE  63U

/* STM32L4 PMA byte offsets. EP0 IN/OUT and CDC/HID buffers do not overlap. */
#define CRABIT_USB_PMA_BTABLE         0x000U
#define CRABIT_USB_PMA_BTABLE_SIZE    0x040U
#define CRABIT_USB_PMA_EP0_OUT        0x040U
#define CRABIT_USB_PMA_EP0_IN         0x080U
#define CRABIT_USB_PMA_CDC_IN         0x0C0U
#define CRABIT_USB_PMA_CDC_OUT        0x100U
#define CRABIT_USB_PMA_CDC_CMD        0x140U
#define CRABIT_USB_PMA_HID_IN         0x148U
#define CRABIT_USB_PMA_HID_OUT        0x150U
#define CRABIT_USB_PMA_END            0x154U
#define CRABIT_USB_PMA_CAPACITY       0x400U

#ifdef __cplusplus
#define CRABIT_USB_STATIC_ASSERT(condition, message) static_assert((condition), message)
#else
#define CRABIT_USB_STATIC_ASSERT(condition, message) _Static_assert((condition), message)
#endif
CRABIT_USB_STATIC_ASSERT((CRABIT_USB_PMA_BTABLE + CRABIT_USB_PMA_BTABLE_SIZE) <= CRABIT_USB_PMA_EP0_OUT, "BTABLE overlap");
CRABIT_USB_STATIC_ASSERT((CRABIT_USB_PMA_EP0_OUT + 64U) <= CRABIT_USB_PMA_EP0_IN, "EP0 OUT overlap");
CRABIT_USB_STATIC_ASSERT((CRABIT_USB_PMA_EP0_IN + 64U) <= CRABIT_USB_PMA_CDC_IN, "EP0 IN overlap");
CRABIT_USB_STATIC_ASSERT((CRABIT_USB_PMA_CDC_IN + 64U) <= CRABIT_USB_PMA_CDC_OUT, "CDC IN overlap");
CRABIT_USB_STATIC_ASSERT((CRABIT_USB_PMA_CDC_OUT + 64U) <= CRABIT_USB_PMA_CDC_CMD, "CDC OUT overlap");
CRABIT_USB_STATIC_ASSERT((CRABIT_USB_PMA_CDC_CMD + 8U) <= CRABIT_USB_PMA_HID_IN, "CDC command overlap");
CRABIT_USB_STATIC_ASSERT((CRABIT_USB_PMA_HID_IN + 8U) <= CRABIT_USB_PMA_HID_OUT, "HID IN overlap");
CRABIT_USB_STATIC_ASSERT((CRABIT_USB_PMA_HID_OUT + 4U) <= CRABIT_USB_PMA_CAPACITY, "HID OUT overflow");
CRABIT_USB_STATIC_ASSERT(CRABIT_USB_PMA_END >= (CRABIT_USB_PMA_HID_OUT + CRABIT_USB_HID_OUT_SIZE), "PMA end before HID OUT buffer");
CRABIT_USB_STATIC_ASSERT(CRABIT_USB_PMA_END <= CRABIT_USB_PMA_CAPACITY, "PMA overflow");
CRABIT_USB_STATIC_ASSERT((CRABIT_USB_PMA_BTABLE % 4U) == 0U && (CRABIT_USB_PMA_EP0_OUT % 4U) == 0U &&
                         (CRABIT_USB_PMA_EP0_IN % 4U) == 0U && (CRABIT_USB_PMA_CDC_IN % 4U) == 0U &&
                         (CRABIT_USB_PMA_CDC_OUT % 4U) == 0U && (CRABIT_USB_PMA_CDC_CMD % 4U) == 0U &&
                         (CRABIT_USB_PMA_HID_IN % 4U) == 0U && (CRABIT_USB_PMA_HID_OUT % 4U) == 0U &&
                         (CRABIT_USB_PMA_END % 4U) == 0U, "PMA offsets must be word aligned");
#undef CRABIT_USB_STATIC_ASSERT

#endif
